#!/usr/bin/env node
/**
 * Required native copy: one wording, two renderings.
 *
 * The path-scoped compliance guards read web sources — `scripts/check-terms.mjs` greps an explicit
 * file list, `scripts/check-neutrality-claims.mjs` scans a path prefix — so copy authored directly
 * in Swift is copy no register governs. ADR 0018 D9 resolves that by never authoring it there: the
 * notices the native core renders inline are declared once in `docs/legal/native-copy.json` and
 * emitted mechanically into a generated Swift file.
 *
 * This guard closes both ends of that pipeline, and fails closed on either:
 *
 *   1. **Registry ↔ web.** Every registered notice must appear verbatim in the web source it names,
 *      compared with markup and whitespace normalised away. Rewording the web copy without updating
 *      the register therefore breaks the build instead of silently leaving the app saying the old
 *      thing — which is the drift this exists to prevent.
 *   2. **Registry ↔ Swift.** The generated file must be exactly what this registry renders. A
 *      hand-edit to the Swift is not a second opinion about the wording; it is an unreviewed change
 *      to legally-registered copy, so it is a build failure.
 *
 * Modal- and print-shaped chrome (the Terms gate, the print authorisation, the plan authorisation
 * band) is deliberately absent: it renders in the WebView islands of D8, where the web source IS the
 * rendering and no second copy exists to govern.
 *
 * Usage: `node scripts/check-native-copy.mjs` to verify, `--write` to regenerate the Swift.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { stripComments } from "./check-neutrality-claims.mjs";

const GENERATED_HEADER = "// Generated by scripts/check-native-copy.mjs — DO NOT EDIT.";
/** Keeps the generated file inside the tree `check-neutrality-claims.mjs` scans (SCAN_PREFIXES). */
const GENERATED_PATH_RE = /^apps\/mobile\/ios\/App\/App\/[\w/-]+\.swift$/;

/**
 * Reduce markup-bearing source text to the words a reader sees, so a registered notice can be
 * matched against copy that is wrapped, indented and tag-interrupted in its source.
 *
 * Svelte splits a sentence across lines and puts `<b>` mid-clause, and TypeScript holds the same
 * words inside a quoted literal. Tags become a space (never nothing: `a<br>b` is two words), the
 * handful of entities that appear in this copy are decoded, and all whitespace collapses.
 *
 * Comments are removed FIRST, and that is load-bearing rather than tidiness: a reworded notice
 * routinely leaves its previous wording behind in a `// was: …` note or a commented-out block, and
 * matching against that text would report the register as satisfied by copy no voter can read —
 * passing precisely when the drift this guard exists to catch has occurred.
 *
 * @param {string} text
 * @returns {string}
 */
export function normaliseCopy(text) {
  if (typeof text !== "string") return "";
  // Human-facing attribute values are copy, and stripping tags wholesale would drop them. A tooltip
  // or a screen-reader label that only ever lives in an attribute is exactly the copy no other guard
  // reads, so it is lifted out of the tag before the tag is removed.
  const withAttributeCopy = stripComments(text).replace(
    /<[^>]*>/g,
    (tag) =>
      ` ${[...tag.matchAll(/\b(?:title|aria-label|alt|placeholder)=(?:"([^"]*)"|'([^']*)')/g)]
        .map((m) => m[1] ?? m[2])
        .join(" ")} `,
  );
  return withAttributeCopy
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * The placeholder a registered notice uses where the web interpolates a value.
 *
 * Most user-facing copy carries a number or a year, and a register that could only hold fixed
 * sentences could only hold the copy that happens not to. That is the wrong half to guard: the
 * sentences with a value in them are the ones that state a quantity.
 */
const PLACEHOLDER = "{}";

/**
 * The shortest a segment either side of a placeholder may be.
 *
 * A registered notice is split on its placeholders and each part must appear, in order, in the web
 * source. Short parts would make that trivial to satisfy — "of" appears in any page — so a segment
 * has to be long enough that finding it means something. Only the FIRST and LAST segments may be
 * shorter, because a notice may legitimately begin or end with a value.
 */
const MIN_SEGMENT = 12;

/**
 * Split a registered notice on its placeholders.
 *
 * @param {string} text
 * @returns {string[]}
 */
export function segments(text) {
  return String(text ?? "").split(PLACEHOLDER);
}

/**
 * Render the registry as the Swift the native core compiles against.
 *
 * A caseless enum rather than a struct: these are constants with no instance to make, and the
 * compiler refuses `LegalCopy()` outright rather than allowing a pointless one.
 *
 * @param {{entries?: unknown}} registry
 * @returns {string}
 */
export function renderSwift(registry) {
  const entries = Array.isArray(registry?.entries) ? registry.entries : [];
  const lines = [
    GENERATED_HEADER,
    "//",
    "// Source of truth: docs/legal/native-copy.json (ADR 0018 D9).",
    "// Regenerate with `node scripts/check-native-copy.mjs --write`.",
    "//",
    "// These notices are legally registered copy backed by the control register. Editing them here",
    "// changes what a voter is told without changing what the compliance guards read, so the build",
    "// rejects any edit that does not come from the registry.",
    "",
    "enum LegalCopy {",
  ];
  for (const [i, e] of entries.entries()) {
    if (i > 0) lines.push("");
    // Collapsed to one line: a note carrying a newline would put bare prose on the next line of
    // the generated file, outside any comment, and the file would not compile.
    if (e?.note) lines.push(`    /// ${String(e.note).replace(/\s+/g, " ").trim()}`);
    const parts = segments(e?.text ?? "");
    if (parts.length === 1) {
      lines.push(`    static let ${e?.swiftName} = ${swiftLiteral(parts[0])}`);
    } else {
      // A notice with values in it becomes a function, so the call site cannot forget one or put
      // them in the wrong order — the compiler asks for exactly as many as the register declares.
      const args = parts
        .slice(1)
        .map((_, i) => `_ v${i + 1}: String`)
        .join(", ");
      const body = parts
        .map((part, i) => (i === 0 ? swiftLiteral(part) : `String(v${i}) + ${swiftLiteral(part)}`))
        .join(" + ");
      lines.push(`    static func ${e?.swiftName}(${args}) -> String {`);
      lines.push(`        ${body}`);
      lines.push("    }");
    }
  }
  lines.push("}", "");
  return lines.join("\n");
}

/**
 * Quote a string as a Swift literal. The copy is prose — em dashes, apostrophes, non-ASCII — so only
 * the two characters that would end or escape the literal need handling.
 *
 * @param {string} s
 * @returns {string}
 */
function swiftLiteral(s) {
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/**
 * Swift keywords that are also plausible notice names. A keyword passes the camel-case test and
 * still fails to compile, so it is rejected in the register rather than discovered in Xcode.
 */
const SWIFT_KEYWORDS = new Set(
  (
    "associatedtype as break case catch class continue default defer deinit do else enum extension " +
    "fallthrough false fileprivate for func guard if import in init inout internal is let nil open " +
    "operator private protocol public repeat rethrows return self static struct subscript super " +
    "switch throw throws true try typealias var where while"
  ).split(" "),
);

/**
 * True when the string carries a C0 control or DEL. Tested by code point rather than by a character
 * class, which lets the source stay free of literal control characters (`no-control-regex`).
 *
 * @param {string} s
 * @returns {boolean}
 */
function hasControlChar(s) {
  for (const ch of s) {
    const c = ch.codePointAt(0);
    if (c < 0x20 || c === 0x7f) return true;
  }
  return false;
}

/**
 * @param {unknown} v
 * @returns {v is string}
 */
const isNonEmptyString = (v) => typeof v === "string" && v.trim().length > 0;

/**
 * Verify both ends of the pipeline.
 *
 * @param {object} input
 * @param {unknown} input.registry           parsed docs/legal/native-copy.json
 * @param {Record<string, string | null>} input.webSources  webSource path -> text (null = unreadable)
 * @param {string | null} input.generated    the generated Swift on disk (null = missing)
 * @returns {{ok: boolean, errors: string[]}}
 */
export function verifyNativeCopy(input) {
  const errors = [];
  const push = (m) => errors.push(m);

  const registry = input?.registry;
  if (!registry || typeof registry !== "object") {
    return { ok: false, errors: ["native-copy registry: could not read (fail closed)"] };
  }

  const entries = Array.isArray(registry.entries) ? registry.entries : null;
  if (!entries || entries.length === 0) {
    return { ok: false, errors: ["native-copy registry: no entries (fail closed)"] };
  }

  const seenIds = new Set();
  const seenSwift = new Set();

  for (const [i, e] of entries.entries()) {
    const at = `entries[${i}]${isNonEmptyString(e?.id) ? ` (${e.id})` : ""}`;

    if (!e || typeof e !== "object") {
      push(`${at}: not an object`);
      continue;
    }
    for (const field of ["id", "swiftName", "text", "webSource"]) {
      if (!isNonEmptyString(e[field])) push(`${at}: missing ${field}`);
    }
    if (!isNonEmptyString(e.id) || !isNonEmptyString(e.swiftName) || !isNonEmptyString(e.text)) {
      continue;
    }

    // A newline (or any control character) would terminate the generated literal mid-string and
    // the file would not compile. Registered copy is a sentence, never a block.
    if (hasControlChar(e.text)) {
      push(
        `${at}: text contains a control character or line break — notices must be a single line`,
      );
    }

    if (seenIds.has(e.id)) push(`${at}: duplicate id`);
    seenIds.add(e.id);
    if (seenSwift.has(e.swiftName)) push(`${at}: duplicate swiftName "${e.swiftName}"`);
    seenSwift.add(e.swiftName);

    // A Swift identifier, so the generated file cannot fail to compile because of a register edit.
    if (!/^[a-z][A-Za-z0-9]*$/.test(e.swiftName)) {
      push(`${at}: swiftName "${e.swiftName}" is not a lower-camel-case Swift identifier`);
    } else if (SWIFT_KEYWORDS.has(e.swiftName)) {
      // `static let default = …` is well-formed camel case and still will not compile.
      push(`${at}: swiftName "${e.swiftName}" is a Swift keyword`);
    }

    if (!isNonEmptyString(e.webSource)) continue;
    const source = input?.webSources?.[e.webSource];
    if (source === undefined || source === null) {
      push(`${at}: could not read webSource ${e.webSource} (fail closed)`);
      continue;
    }
    const haystack = normaliseCopy(source);
    const parts = segments(e.text).map(normaliseCopy);

    // Every part has to be long enough that finding it means something, or a notice could be
    // chopped into fragments that appear on any page and the check would pass on nothing.
    const shortInterior = parts
      .slice(1, -1)
      .some((part) => part.length > 0 && part.length < MIN_SEGMENT);
    if (shortInterior) {
      push(
        `${at}: a segment between placeholders is shorter than ${MIN_SEGMENT} characters — too ` +
          `short to prove the wording is the web's`,
      );
      continue;
    }

    // In order, and at increasing positions: the parts of a sentence appearing somewhere on the
    // page in any arrangement is not the same sentence.
    let cursor = 0;
    let matched = true;
    for (const part of parts) {
      if (part.length === 0) continue;
      const found = haystack.indexOf(part, cursor);
      if (found === -1) {
        matched = false;
        break;
      }
      cursor = found + part.length;
    }

    if (!matched) {
      push(
        `${at}: registered wording is not present in ${e.webSource} — the web copy was reworded ` +
          `without updating this register, so the native app would keep stating the old wording: ` +
          `"${normaliseCopy(e.text)}"`,
      );
    }
  }

  // The output path is part of the register, so a stray edit could aim the generator at a file no
  // guard scans, leaving the real LegalCopy.swift orphaned and stale while this check still passes.
  const generatedPath = input?.generatedPath;
  if (generatedPath !== undefined) {
    if (!isNonEmptyString(generatedPath) || !GENERATED_PATH_RE.test(generatedPath)) {
      push(
        `generated: "${generatedPath}" must be a .swift file under the iOS app target, so the ` +
          `neutrality scan covers it`,
      );
    }
  }

  const generated = input?.generated;
  if (generated === undefined || generated === null) {
    push(
      `generated file missing — run \`node scripts/check-native-copy.mjs --write\` and commit it`,
    );
  } else if (generated !== renderSwift(registry)) {
    push(
      `generated file is out of sync with the registry (hand-edited, or the register changed) — ` +
        `run \`node scripts/check-native-copy.mjs --write\` and commit the result`,
    );
  }

  return { ok: errors.length === 0, errors };
}

/* c8 ignore start -- CLI/fs plumbing, exercised via CI not unit tests */
const ROOT = new URL("../", import.meta.url);
const rel = (p) => fileURLToPath(new URL(p, ROOT));
const REGISTRY = "docs/legal/native-copy.json";

function safeRead(relPath) {
  try {
    return readFileSync(rel(relPath), "utf8");
  } catch {
    return null;
  }
}

function main() {
  const raw = safeRead(REGISTRY);
  if (raw === null) {
    console.error(`::error::cannot read ${REGISTRY}`);
    process.exit(1);
  }

  let registry;
  try {
    registry = JSON.parse(raw);
  } catch (err) {
    console.error(`::error::${REGISTRY} is not valid JSON: ${err.message}`);
    process.exit(1);
  }

  const out = isNonEmptyString(registry.generated)
    ? registry.generated
    : "apps/mobile/ios/App/App/Generated/LegalCopy.swift";

  if (process.argv.includes("--write")) {
    const swift = renderSwift(registry);
    mkdirSync(dirname(rel(out)), { recursive: true });
    writeFileSync(rel(out), swift, "utf8");
    console.info(`wrote ${out} (${registry.entries?.length ?? 0} notices)`);
    return;
  }

  const webSources = {};
  for (const e of Array.isArray(registry.entries) ? registry.entries : []) {
    if (isNonEmptyString(e?.webSource)) webSources[e.webSource] = safeRead(e.webSource);
  }

  const { ok, errors } = verifyNativeCopy({
    registry,
    webSources,
    generatedPath: out,
    generated: safeRead(out),
  });

  if (!ok) {
    for (const e of errors) console.error(`::error::native copy: ${e}`);
    process.exit(1);
  }
  console.info(`native copy: ${registry.entries.length} notices in sync (registry, web, ${out})`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
