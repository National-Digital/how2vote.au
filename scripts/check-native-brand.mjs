#!/usr/bin/env node
/**
 * One wordmark, two renderings.
 *
 * `apps/web/src/lib/brand/mark.mjs` is the single source of truth for the logo: Newsreader outlines
 * baked to absolute coordinates so the mark renders identically with **zero font dependency**, in
 * the Logo component, the favicon, the PWA icons and the OpenGraph cards. A native screen drawing
 * the name as `Text("how2vote")` is not a second rendering of that mark — it is a different mark,
 * in whatever face the platform picks, missing the boxed preference numeral the mark is built
 * around. That is exactly the platform drift the baked outlines exist to prevent.
 *
 * So the geometry is emitted mechanically into Swift, and this guard fails closed on either end:
 *
 *   1. **Source → Swift.** The generated file must be exactly what `mark.mjs` renders. A hand-edit
 *      to the Swift is not a second opinion about the logo; it is an unreviewed change to the brand.
 *   2. **Swift → target.** Covered by `scripts/check-ios-sources.mjs`, which asserts every Swift
 *      file is built — a generated file that never compiles would leave the old wordmark in place.
 *
 * Usage: `node scripts/check-native-brand.mjs` to verify, `--write` to regenerate the Swift.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

export const GENERATED_HEADER = "// Generated by scripts/check-native-brand.mjs — DO NOT EDIT.";

/** Path commands the Swift reader implements. The generator refuses anything else. */
export const SUPPORTED_COMMANDS = new Set(["M", "L", "H", "V", "Q", "Z"]);

/**
 * The commands a path string uses.
 *
 * Lower-case (relative) commands and curve types the reader does not implement would be dropped
 * silently by a lenient parser, which on a logo means a subtly wrong shape rather than a failure.
 */
export function commandsIn(d) {
  return new Set(String(d).match(/[A-Za-z]/g) ?? []);
}

/** @returns {string[]} reasons the mark cannot be rendered natively, empty when it can */
export function unsupportedIn(paths) {
  const problems = [];
  for (const [name, d] of Object.entries(paths)) {
    for (const c of commandsIn(d)) {
      if (!SUPPORTED_COMMANDS.has(c)) {
        problems.push(
          `${name} uses path command "${c}", which the native reader does not implement ` +
            `(supported: ${[...SUPPORTED_COMMANDS].join(", ")})`,
        );
      }
    }
  }
  return problems;
}

/** A Swift literal for a finite number, in a form Swift parses back identically. */
function num(n) {
  if (!Number.isFinite(n)) throw new Error(`not a finite number: ${n}`);
  return Number.isInteger(n) ? `${n}` : `${n}`;
}

/**
 * Renders the Swift constants for the wordmark lockup.
 *
 * Only WORDMARK is emitted: it is the in-app lockup, and the icon/OG variants have no native
 * surface. Adding one is a generator change, not a hand-edit.
 */
export function renderSwift(wordmark) {
  const { width, height, textD, rect, numeralD } = wordmark;
  return `${GENERATED_HEADER}
// Source: apps/web/src/lib/brand/mark.mjs (WORDMARK), itself generated from Newsreader outlines.
//
// The wordmark's own coordinate space, baseline at y = 0 and ink above it in negative y. Consumers
// scale it; nothing here assumes a size.

import CoreGraphics

enum BrandMark {
    /// The lockup's design size, and so its aspect ratio.
    static let size = CGSize(width: ${num(width)}, height: ${num(height)})

    /// "how" + "vote" as filled outlines — everything but the numeral and its box.
    static let textPath = "${textD}"

    /// The ballot-paper box around the preference numeral. Stroked, never filled.
    static let box = (
        x: ${num(rect.x)} as CGFloat,
        y: ${num(rect.y)} as CGFloat,
        width: ${num(rect.width)} as CGFloat,
        height: ${num(rect.height)} as CGFloat,
        rx: ${num(rect.rx)} as CGFloat,
        strokeWidth: ${num(rect.strokeWidth)} as CGFloat
    )

    /// The "2" inside the box, as a filled outline.
    static let numeralPath = "${numeralD}"
}
`;
}

/** @returns {{ok: boolean, errors: string[]}} */
export function verifyNativeBrand({ wordmark, generatedPath, generated }) {
  const errors = [];

  if (!wordmark || typeof wordmark !== "object") {
    return { ok: false, errors: ["WORDMARK could not be read from the brand source"] };
  }
  errors.push(...unsupportedIn({ textD: wordmark.textD, numeralD: wordmark.numeralD }));

  if (generated === null) {
    errors.push(`${generatedPath} is missing — run: node scripts/check-native-brand.mjs --write`);
    return { ok: errors.length === 0, errors };
  }
  if (errors.length === 0 && generated !== renderSwift(wordmark)) {
    errors.push(
      `${generatedPath} does not match the brand source — it was hand-edited, or the mark ` +
        `changed without regenerating. Run: node scripts/check-native-brand.mjs --write`,
    );
  }
  return { ok: errors.length === 0, errors };
}

/* c8 ignore start -- CLI/fs plumbing, exercised via CI not unit tests */
const ROOT = new URL("../", import.meta.url);
const rel = (p) => fileURLToPath(new URL(p, ROOT));
const OUT = "apps/mobile/ios/App/App/Generated/BrandMark.swift";

function safeRead(relPath) {
  try {
    return readFileSync(rel(relPath), "utf8");
  } catch {
    return null;
  }
}

async function main() {
  const { WORDMARK } = await import(new URL("apps/web/src/lib/brand/mark.mjs", ROOT));

  if (process.argv.includes("--write")) {
    const problems = unsupportedIn({ textD: WORDMARK.textD, numeralD: WORDMARK.numeralD });
    if (problems.length > 0) {
      for (const p of problems) console.error(`::error::native brand: ${p}`);
      process.exit(1);
    }
    mkdirSync(dirname(rel(OUT)), { recursive: true });
    writeFileSync(rel(OUT), renderSwift(WORDMARK), "utf8");
    console.info(`wrote ${OUT}`);
    return;
  }

  const { ok, errors } = verifyNativeBrand({
    wordmark: WORDMARK,
    generatedPath: OUT,
    generated: safeRead(OUT),
  });
  if (!ok) {
    for (const e of errors) console.error(`::error::native brand: ${e}`);
    process.exit(1);
  }
  console.info(`native brand OK — the wordmark is one geometry, rendered in Svelte and Swift`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
