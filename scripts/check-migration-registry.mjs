#!/usr/bin/env node
/**
 * @fileoverview Migration checksum registry — pin every D1 migration by SHA-256 and fail closed on
 * drift.
 *
 * Each migration in apps/web/migrations/ is pinned by its SHA-256 in
 * infra/providers/cloudflare/migration-registry.json. Two guarantees:
 *
 *  - COMMITTED drift (CI): the committed registry must exactly match the on-disk migrations — same
 *    files, same order, same bytes. An edited, added or removed migration that isn't reflected in the
 *    registry fails the build. Same `--write` / check drift-gate pattern as generate-license-data.mjs.
 *
 *  - APPLIED drift (deploy): after `wrangler d1 migrations apply`, the set of migrations the live
 *    database reports as applied must equal the registry's file set. A production database carrying an
 *    unpinned migration, or missing a pinned one, fails the deploy closed (an empty applied list is
 *    treated as "could not verify" and rejected).
 *
 * Pure decision logic is exported for unit tests; the fs/CLI plumbing runs only when executed
 * directly.
 *
 * Usage:
 *   node scripts/check-migration-registry.mjs             # check committed registry vs on-disk (CI)
 *   node scripts/check-migration-registry.mjs --write     # regenerate the registry from the .sql files
 *   node scripts/check-migration-registry.mjs --applied "0001_x.sql,0002_y.sql"   # deploy: live set
 */

import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const REGISTRY_VERSION = 1;

/** Migration filenames must be NNNN_name.sql; the numeric prefix defines apply order. */
const MIGRATION_NAME = /^\d{4}_[\w-]+\.sql$/;

/** SHA-256 hex of a string/Buffer. */
export function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

/**
 * Build the registry object from the on-disk migrations (name-sorted).
 * @param {{ name: string, bytes: string | Buffer }[]} files
 * @returns {{ schemaVersion: number, note: string, migrations: { file: string, sha256: string }[] }}
 */
export function buildRegistry(files) {
  const migrations = [...files]
    .sort((a, b) => a.name.localeCompare(b.name, "en"))
    .map((f) => ({ file: f.name, sha256: sha256(f.bytes) }));
  return {
    schemaVersion: REGISTRY_VERSION,
    note: "Generated by scripts/check-migration-registry.mjs — do not edit by hand. Pins each apps/web/migrations/*.sql by SHA-256; the deploy fails if the applied set drifts from this list.",
    migrations,
  };
}

/**
 * COMMITTED drift: compare a committed registry against freshly-hashed on-disk migrations.
 * @param {unknown} registry  parsed migration-registry.json
 * @param {{ name: string, bytes: string | Buffer }[]} files  on-disk .sql files
 * @returns {{ ok: boolean, errors: string[] }}
 */
export function verify(registry, files) {
  const errors = [];
  if (typeof registry !== "object" || registry === null || Array.isArray(registry)) {
    return { ok: false, errors: ["migration-registry: not a JSON object"] };
  }
  if (registry.schemaVersion !== REGISTRY_VERSION) {
    errors.push(`migration-registry: schemaVersion must be ${REGISTRY_VERSION}`);
  }
  const pinned = Array.isArray(registry.migrations) ? registry.migrations : null;
  if (pinned === null)
    return { ok: false, errors: [...errors, "migration-registry: migrations must be an array"] };

  // Validate filenames + reject a registry with nothing pinned (fail closed).
  if (files.length === 0)
    errors.push("migration-registry: no migration .sql files found (fail closed)");
  for (const f of files) {
    if (!MIGRATION_NAME.test(f.name)) {
      errors.push(
        `migration-registry: "${f.name}" is not a valid NNNN_name.sql migration filename`,
      );
    }
  }

  const onDisk = new Map([...files].map((f) => [f.name, sha256(f.bytes)]));
  const registered = new Map(pinned.map((m) => [m?.file, m?.sha256]));

  for (const [name, hash] of onDisk) {
    if (!registered.has(name)) {
      errors.push(
        `migration-registry: "${name}" is not pinned — run \`pnpm infra:migrations:generate\``,
      );
    } else if (registered.get(name) !== hash) {
      errors.push(
        `migration-registry: "${name}" checksum drifted from the registry (edited migration?)`,
      );
    }
  }
  for (const name of registered.keys()) {
    if (!onDisk.has(name)) {
      errors.push(`migration-registry: pinned migration "${name}" is missing on disk`);
    }
  }
  return { ok: errors.length === 0, errors };
}

/**
 * APPLIED drift (deploy): the live database's applied migration set must equal the registry set.
 * @param {unknown} registry  parsed migration-registry.json
 * @param {string[]} appliedNames  migration filenames the live DB reports as applied
 * @returns {{ ok: boolean, errors: string[] }}
 */
export function verifyApplied(registry, appliedNames) {
  const pinned = Array.isArray(registry?.migrations) ? registry.migrations : [];
  const expected = new Set(pinned.map((m) => m?.file).filter(Boolean));
  if (expected.size === 0) {
    return {
      ok: false,
      errors: ["applied: registry pins no migrations — cannot verify (fail closed)"],
    };
  }
  const applied = new Set(
    (Array.isArray(appliedNames) ? appliedNames : []).map((n) => String(n).trim()).filter(Boolean),
  );
  if (applied.size === 0) {
    return {
      ok: false,
      errors: ["applied: live DB reported no applied migrations — cannot verify (fail closed)"],
    };
  }
  const errors = [];
  for (const name of expected) {
    if (!applied.has(name))
      errors.push(`applied: pinned migration "${name}" is NOT applied on the live DB`);
  }
  for (const name of applied) {
    if (!expected.has(name))
      errors.push(`applied: live DB has unpinned migration "${name}" — refusing to deploy`);
  }
  return { ok: errors.length === 0, errors };
}

/* c8 ignore start -- fs/CLI plumbing, exercised via CI not unit tests */
const root = new URL("..", import.meta.url);
const MIGRATIONS_DIR = new URL("apps/web/migrations/", root);
const OUT_PATH = new URL("infra/providers/cloudflare/migration-registry.json", root);

function loadFiles() {
  return readdirSync(MIGRATIONS_DIR)
    .filter((f) => f.endsWith(".sql"))
    .sort()
    .map((name) => ({ name, bytes: readFileSync(new URL(name, MIGRATIONS_DIR)) }));
}

function parseApplied(argv) {
  const i = argv.indexOf("--applied");
  if (i === -1) return null;
  return (argv[i + 1] ?? "")
    .split(/[\s,]+/)
    .map((s) => s.trim())
    .filter(Boolean);
}

function main() {
  const argv = process.argv.slice(2);
  const applied = parseApplied(argv);

  // Deploy mode: compare the live applied set against the committed registry.
  if (applied !== null) {
    let registry;
    try {
      registry = JSON.parse(readFileSync(OUT_PATH, "utf8"));
    } catch (err) {
      console.error(`::error::migration-registry: cannot read registry: ${err.message}`);
      process.exit(1);
      return;
    }
    const { ok, errors } = verifyApplied(registry, applied);
    if (!ok) {
      for (const e of errors) console.error(`::error::migration-registry: ${e}`);
      process.exit(1);
      return;
    }
    console.info(
      `migration-registry OK — live applied set matches the ${registry.migrations.length} pinned migration(s)`,
    );
    return;
  }

  const files = loadFiles();
  const serialised = JSON.stringify(buildRegistry(files), null, 2) + "\n";

  if (argv.includes("--write")) {
    writeFileSync(OUT_PATH, serialised);
    console.info(
      `migration registry written → ${fileURLToPath(OUT_PATH)} (${files.length} migration(s))`,
    );
    return;
  }

  let current;
  try {
    current = readFileSync(OUT_PATH, "utf8");
  } catch {
    console.error(
      "::error::migration-registry: migration-registry.json is missing — run `pnpm infra:migrations:generate`",
    );
    process.exit(1);
    return;
  }
  const registry = JSON.parse(current);
  const { ok, errors } = verify(registry, files);
  if (!ok || current !== serialised) {
    for (const e of errors) console.error(`::error::migration-registry: ${e}`);
    if (current !== serialised) {
      console.error(
        "::error::migration-registry: migration-registry.json is out of date — run `pnpm infra:migrations:generate` and commit the result",
      );
    }
    process.exit(1);
    return;
  }
  console.info(`migration-registry OK — ${files.length} migration(s) pinned and unchanged`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main();
}
