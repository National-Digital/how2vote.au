#!/usr/bin/env node
/**
 * @fileoverview Generate the SIGNED research election registry from the committed datasets.
 *
 * The registry (apps/web/src/lib/research/election-registry.json) is the server-side allowlist of
 * every value a research contribution may carry that is DATASET-derived — the valid election ids, and
 * per election the party-match keys and proposition ids. The ingestion Function loads it and drops any
 * contribution carrying an out-of-registry value (poisoning prevention). It is content-addressed: an
 * `integrity` sha-256 digest over its `{version, elections}` body makes tampering with the deployed
 * artefact detectable (verified by scripts/check-research-integrity.mjs and at runtime by registry.ts).
 * The election `open` flags, schema/consent versions and the stance/demographic allowlists are NOT in
 * this file — they come from consent.ts + survey.ts so there is a single source for each; registry.ts
 * merges the two.
 *
 * This is the same drift-gate pattern as generate-license-data.mjs / generate-vendor-allowlist.mjs:
 * `--write` regenerates the committed file; the default (CI) mode fails if it has drifted from what the
 * datasets would produce.
 *
 * The pure builders are exported for unit tests; the fs/CLI plumbing runs only when executed directly.
 *
 * Usage:
 *   node scripts/generate-research-registry.mjs            # check (fail on drift)
 *   node scripts/generate-research-registry.mjs --write    # regenerate from the datasets
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** Registry format version (bump on a structural change to this file's shape). */
export const REGISTRY_VERSION = 1;

/** Sort + de-duplicate strings deterministically (ASCII order for stable, locale-free output). */
function uniqSortedStrings(values) {
  return [...new Set(values)].sort();
}

/** Sort + de-duplicate a list of positive integers ascending. */
function uniqSortedInts(values) {
  return [...new Set(values)].sort((a, b) => a - b);
}

/**
 * Extract one election's allowlist from its compiled dataset.
 * @param {unknown} dataset  parsed data/dist/<id>/dataset.json
 * @returns {{ parties: string[], propositionIds: number[] }}
 */
export function electionAllowlist(dataset) {
  const d = dataset && typeof dataset === "object" ? dataset : {};
  const parties = Array.isArray(d.parties?.parties)
    ? d.parties.parties.map((p) => p?.key).filter((k) => typeof k === "string")
    : [];
  const questions = Array.isArray(d.questions?.questions)
    ? d.questions.questions.map((q) => q?.id).filter((id) => Number.isInteger(id) && id > 0)
    : [];
  return { parties: uniqSortedStrings(parties), propositionIds: uniqSortedInts(questions) };
}

/**
 * Build the registry body (the signed part) from the election list + their datasets.
 * @param {{ id: string }[]} elections  parsed data/dist/elections.json
 * @param {Record<string, unknown>} datasets  election id → parsed dataset
 * @returns {{ version: number, elections: Record<string, { parties: string[], propositionIds: number[] }> }}
 */
export function buildRegistryBody(elections, datasets) {
  const ids = uniqSortedStrings(elections.map((e) => e.id));
  /** @type {Record<string, { parties: string[], propositionIds: number[] }>} */
  const out = {};
  for (const id of ids) {
    out[id] = electionAllowlist(datasets[id]);
  }
  return { version: REGISTRY_VERSION, elections: out };
}

/**
 * Content-addressed integrity digest over the registry body. The body is re-serialised in a fixed key
 * order (version, then elections by sorted id, each with parties then propositionIds) so the digest is
 * deterministic and independent of incidental JSON key ordering.
 * @param {{ version: number, elections: Record<string, { parties: string[], propositionIds: number[] }> }} body
 * @returns {string} `sha256-<hex>`
 */
export function registryDigest(body) {
  const canonicalElections = {};
  for (const id of Object.keys(body.elections).sort()) {
    const e = body.elections[id];
    canonicalElections[id] = {
      parties: [...e.parties].sort(),
      propositionIds: [...e.propositionIds].sort((a, b) => a - b),
    };
  }
  const canonical = JSON.stringify({ version: body.version, elections: canonicalElections });
  return "sha256-" + createHash("sha256").update(canonical).digest("hex");
}

/** Assemble the full committed file (body + provenance metadata + integrity digest). */
export function buildRegistryFile(elections, datasets) {
  const body = buildRegistryBody(elections, datasets);
  return {
    version: body.version,
    generatedFrom: "data/dist",
    note: "Generated by scripts/generate-research-registry.mjs — do not edit by hand. The integrity digest signs the {version, elections} body; the ingestion Function drops any out-of-registry value.",
    integrity: registryDigest(body),
    elections: body.elections,
  };
}

/* c8 ignore start -- fs/CLI plumbing, exercised via CI not unit tests */
const DIST_DIR = new URL("../data/dist/", import.meta.url);
const OUT_PATH = new URL("../apps/web/src/lib/research/election-registry.json", import.meta.url);

function loadDatasets() {
  const elections = JSON.parse(readFileSync(new URL("elections.json", DIST_DIR), "utf8"));
  const datasets = {};
  const dirs = readdirSync(DIST_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name);
  for (const id of dirs) {
    try {
      datasets[id] = JSON.parse(readFileSync(new URL(`${id}/dataset.json`, DIST_DIR), "utf8"));
    } catch {
      // A listed directory without a compiled dataset contributes an empty allowlist.
    }
  }
  return { elections, datasets };
}

function main() {
  const write = process.argv.includes("--write");
  const { elections, datasets } = loadDatasets();
  const generated = buildRegistryFile(elections, datasets);
  const serialised = JSON.stringify(generated, null, 2) + "\n";

  if (write) {
    writeFileSync(OUT_PATH, serialised);
    console.info(`research registry written → ${fileURLToPath(OUT_PATH)}`);
    return;
  }

  let current = "";
  try {
    current = readFileSync(OUT_PATH, "utf8");
  } catch {
    console.error(
      "::error::research-registry: election-registry.json is missing — run `pnpm research-registry:generate`",
    );
    process.exit(1);
  }
  if (current !== serialised) {
    console.error(
      "::error::research-registry: election-registry.json is out of date — run `pnpm research-registry:generate` and commit the result",
    );
    process.exit(1);
  }
  console.info("research registry OK — election-registry.json matches the datasets");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main();
}
