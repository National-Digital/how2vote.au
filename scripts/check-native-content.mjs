function swiftFiles(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) return swiftFiles(p);
    return f.endsWith(".swift") ? [p] : [];
  });
}

/** The parse of a source, through a temporary copy so a commit's version can be read too. */
function dumpParse(dir, name, source) {
  const path = join(dir, name);
  writeFileSync(path, source);
  return execFileSync(process.env.SWIFTC || "swiftc", ["-dump-parse", name], {
    cwd: dir,
    maxBuffer: 1 << 28,
    stdio: ["ignore", "pipe", "pipe"],
  }).toString();
}

/** Every Swift file's hand-written copy, read through `read` (the tree, or a commit). */
function scan(files, read) {
  const dir = mkdtempSync(join(tmpdir(), "native-content-"));
  try {
    const found = {};
    for (const file of files) {
      const source = read(file);
      if (generatorOf(file, source)) continue;
      const model = file.startsWith(`${APP}/Model/`);
      const dump = dumpParse(dir, basename(file), everyBranch(source));
      const texts = handWrittenCopy(dump, { source, model });
      if (texts.length > 0) found[file] = texts;
    }
    return found;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/**
 * Runs the fixtures through this compiler and holds each to its recorded result, so a parse this
 * reader no longer understands fails instead of finding nothing.
 */
function checkFixtures(write) {
  const expected = JSON.parse(readFileSync(join(ROOT, FIXTURES, "expected.json"), "utf8"));
  const dir = mkdtempSync(join(tmpdir(), "native-content-fixtures-"));
  const errors = [];
  try {
    for (const [name, { model = false, copy }] of Object.entries(expected)) {
      const source = readFileSync(join(ROOT, FIXTURES, `${name}.swift`), "utf8");
      const dump = dumpParse(dir, `${name}.swift`, everyBranch(source));
      if (write) writeFileSync(join(ROOT, FIXTURES, `${name}.dump`), dump);
      const got = handWrittenCopy(dump, { source, model });
      if (JSON.stringify(got) !== JSON.stringify(copy)) {
        errors.push(`the ${name} fixture reads ${JSON.stringify(got)} through this compiler`);
      }
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
  return errors;
}

function main() {
  const fixtureErrors = checkFixtures(process.argv.includes("--write-fixtures"));
  if (fixtureErrors.length > 0) {
    for (const e of fixtureErrors) console.error(`::error::native content: ${e}`);
    process.exit(1);
  }

  const files = swiftFiles(join(ROOT, APP)).map((f) => relative(ROOT, f));
  const current = scan(files, (f) => readFileSync(join(ROOT, f), "utf8"));

  if (process.argv.includes("--write")) {
    writeFileSync(join(ROOT, DEBT), JSON.stringify(current, null, 2) + "\n");
    console.info(`native content: recorded ${debtSize(current)} hand-written string(s) as debt`);
    return;
  }

  const debt = JSON.parse(readFileSync(join(ROOT, DEBT), "utf8"));
  let base = null;
  const ref = process.env.NATIVE_CONTENT_BASE;
  if (ref) {
    const git = (args) => execFileSync("git", args, { cwd: ROOT, maxBuffer: 1 << 26 }).toString();
    const mergeBase = git(["merge-base", ref, "HEAD"]).trim();
    const baseFiles = git(["ls-tree", "-r", "--name-only", mergeBase, "--", APP])
      .split("\n")
      .filter((f) => f.endsWith(".swift"));
    base = scan(baseFiles, (f) => git(["show", `${mergeBase}:${f}`]));
  }

  const errors = [];
  // Each exemption's generator must be one CI runs, or the exemption vouches for nothing.
  const workflows = join(ROOT, ".github/workflows");
  const workflow = readdirSync(workflows)
    .map((f) => readFileSync(join(workflows, f), "utf8"))
    .join("\n");
  for (const [file, generator] of Object.entries(GENERATED)) {
    if (!workflow.includes(`node ${generator}`)) {
      errors.push(`${file} is exempt as ${generator}'s, but CI never runs ${generator}`);
    }
  }
  for (const file of files) {
    const source = readFileSync(join(ROOT, file), "utf8");
    if (/^import SwiftUI\b/m.test(source) && showsAnError(source)) {
      errors.push(`${file} shows an error's description on screen`);
    }
  }
  errors.push(...verifyNativeContent(current, debt, base));
  if (errors.length > 0) {
    for (const e of errors) console.error(`::error::native content: ${e}`);
    process.exit(1);
  }
  const listed = Object.keys(debt).length;
  console.info(
    `native content OK — no new hand-written copy; ${debtSize(debt)} string(s) in ${listed} ` +
      `file(s) still to move to the web build`,
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
