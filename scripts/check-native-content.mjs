/**
 * Parses `swiftc -dump-parse` output into nodes: `{ kind, head, children }`, where `head` is the text
 * of the node's own line — its attributes — and `kind` its first word.
 *
 * @param {string} dump
 */
export function parseDump(dump) {
  const root = { kind: "root", head: "", children: [] };
  const stack = [root];
  let i = 0;
  while (i < dump.length) {
    const c = dump[i];
    if (c === "(") {
      let j = i + 1;
      let head = "";
      while (j < dump.length && dump[j] !== "(" && dump[j] !== ")") {
        if (dump[j] === '"') {
          const start = j++;
          while (j < dump.length && dump[j] !== '"') j += dump[j] === "\\" ? 2 : 1;
          head += dump.slice(start, ++j);
        } else {
          head += dump[j++];
        }
      }
      // `original_init=string_literal_expr …`: the role is a prefix on the node's kind.
      const trimmed = head.trim();
      const role = /^(\w+)=/.exec(trimmed)?.[1] ?? null;
      const kind = (trimmed.split(/\s/, 1)[0] ?? "").replace(/^\w+=/, "");
      const node = { kind, role, head, children: [] };
      stack.at(-1).children.push(node);
      stack.push(node);
      i = j;
    } else if (c === ")") {
      if (stack.length === 1) throw new Error("the parse dump closes a node it never opened");
      stack.pop();
      i++;
    } else {
      i++;
    }
  }
  if (stack.length !== 1) throw new Error("the parse dump ends inside a node");
  return root;
}

/** Decodes the dump's escaping of a quoted value: `\xHH` bytes of UTF-8, and C escapes. */
function unescape(quoted) {
  const bytes = [];
  const body = quoted.slice(1, -1);
  for (let i = 0; i < body.length; i++) {
    if (body[i] !== "\\") {
      bytes.push(...Buffer.from(body[i], "utf8"));
      continue;
    }
    const e = body[++i];
    if (e === "x") {
      bytes.push(parseInt(body.slice(i + 1, i + 3), 16));
      i += 2;
    } else {
      bytes.push({ n: 10, t: 9, r: 13, 0: 0 }[e] ?? e.charCodeAt(0));
    }
  }
  return Buffer.from(bytes).toString("utf8");
}

/** A node's attribute, decoded, or null. */
export function attr(node, name) {
  const m = new RegExp(`(?:^|\\s)${name}=("(?:[^"\\\\]|\\\\.)*"|\\S+)`).exec(node.head);
  if (!m) return null;
  return m[1].startsWith('"') ? unescape(m[1]) : m[1];
}

/** A string literal's value, which the parse must give: one it does not is a dump misread. */
function valueOf(literal) {
  const value = literal?.kind === "string_literal_expr" ? attr(literal, "value") : null;
  if (value === null) throw new Error("a string literal in the parse carries no value");
  return value;
}

const isImplicit = (node) => /^\S+ implicit\b/.test(node.head.trim());
const bare = (field) => (field ?? "").replace(/\(.*$/, "");

/** A call's callee: `name`, `base.field` (`.field` on an expression), or `.member`. */
export function callee(call) {
  const fn = call.children[0];
  if (!fn) return "";
  if (fn.kind === "unresolved_decl_ref_expr") return attr(fn, "name") ?? "";
  if (fn.kind === "unresolved_member_expr") return `.${bare(attr(fn, "name"))}`;
  if (fn.kind === "unresolved_dot_expr") {
    const base = fn.children[0];
    const owner =
      base?.kind === "unresolved_decl_ref_expr"
        ? attr(base, "name")
        : base?.kind === "unresolved_dot_expr"
          ? bare(attr(base, "field"))
          : "";
    return `${owner}.${bare(attr(fn, "field"))}`;
  }
  return "";
}

const interpolationStep = (call) =>
  call.kind === "call_expr" && call.children[0]?.kind === "unresolved_dot_expr"
    ? (/^append(Literal|Interpolation)\b/.exec(attr(call.children[0], "field") ?? "")?.[1] ?? null)
    : null;

/**
 * Every literal in a parsed file, with the chain of nodes above it: an interpolated literal as one
 * template (`{}` for each interpolation), and the literals nested inside an interpolation on their
 * own. A pattern binding's initialiser is printed twice, as written and as processed, and an enum
 * element twice, in its `case` and as a member; each is read once.
 */
export function literalsOf(root) {
  const found = [];
  const walk = (node, path) => {
    if (node.role === "processed_init") return;
    if (node.kind === "enum_element_decl" && path.at(-1)?.kind !== "enum_case_decl") return;
    if (node.kind === "interpolated_string_literal_expr") {
      let text = "";
      const segments = (n) => {
        for (const child of n.children) {
          const step = interpolationStep(child);
          if (step === "Literal") text += valueOf(child.children[1]?.children[0]?.children[0]);
          else if (step === "Interpolation") text += "{}";
          else segments(child);
        }
      };
      segments(node);
      found.push({ text, path });
    } else if (node.kind === "string_literal_expr") {
      // An interpolation's literal segment is part of its template, counted there.
      const parent = path.at(-3);
      if (!(parent && interpolationStep(parent) === "Literal")) {
        found.push({ text: valueOf(node), path });
      }
    }
    for (const child of node.children) walk(child, [...path, node]);
  };
  walk(root, []);
  return found;
}

/**
 * Every string literal in a Swift source, read from its text: each as Swift decodes it, `{}` for each
 * interpolation, and the literals inside an interpolation on their own. Comments are skipped.
 *
 * @param {string} source
 * @returns {string[]}
 */
export function lexLiterals(source) {
  const found = [];
  const opensString = (j) => /^#*"/.test(source.slice(j, j + 8));
  const skipComment = (j) => {
    if (source.startsWith("//", j)) {
      const end = source.indexOf("\n", j);
      return end < 0 ? source.length : end;
    }
    if (source.startsWith("/*", j)) {
      let depth = 0;
      for (let k = j; k < source.length; k++) {
        if (source.startsWith("/*", k)) {
          depth++;
          k++;
        } else if (source.startsWith("*/", k) && --depth === 0) return k + 2;
      }
      return source.length;
    }
    return j;
  };
  /** Reads the literal opening at `i`, returning the index just past it. */
  const string = (i) => {
    let hashes = 0;
    while (source[i + hashes] === "#") hashes++;
    let j = i + hashes;
    const multi = source.startsWith('"""', j);
    j += multi ? 3 : 1;
    const close = (multi ? '"""' : '"') + "#".repeat(hashes);
    const escape = "\\" + "#".repeat(hashes);
    let text = "";
    while (j < source.length) {
      if (source.startsWith(close, j)) {
        found.push(text);
        return j + close.length;
      }
      if (source.startsWith(escape, j)) {
        const k = j + escape.length;
        const c = source[k];
        if (c === "(") {
          j = interpolation(k);
          text += "{}";
        } else if (c === "u" && source[k + 1] === "{") {
          const end = source.indexOf("}", k);
          text += String.fromCodePoint(parseInt(source.slice(k + 2, end), 16));
          j = end + 1;
        } else {
          text += { n: "\n", t: "\t", r: "\r", 0: "\0" }[c] ?? c;
          j = k + 1;
        }
        continue;
      }
      if (!multi && source[j] === "\n") throw new Error("a string literal runs past its line");
      text += source[j++];
    }
    throw new Error("a string literal is never closed");
  };
  /** Reads the interpolation whose `(` is at `open`, returning the index just past its `)`. */
  const interpolation = (open) => {
    let depth = 0;
    for (let j = open; j < source.length;) {
      if (opensString(j)) {
        j = string(j);
        continue;
      }
      const past = skipComment(j);
      if (past !== j) {
        j = past;
        continue;
      }
      if (source[j] === "(") depth++;
      else if (source[j] === ")" && --depth === 0) return j + 1;
      j++;
    }
    throw new Error("an interpolation is never closed");
  };
  for (let j = 0; j < source.length;) {
    const past = skipComment(j);
    if (past !== j) j = past;
    else if (opensString(j)) j = string(j);
    else j++;
  }
  return found;
}

/** The source with its conditional-compilation directives blanked, so every branch is parsed. */
export const everyBranch = (source) =>
  source.replace(/^[ \t]*#(?:if|elseif|else|endif)\b.*$/gm, "");

const isAscii = (text) => [...text].every((c) => c.charCodeAt(0) < 128);

/** The words of a literal: its text without interpolations or format directives (`%02x`). */
const wordsOf = (text) => text.replace(/\{\}/g, "").replace(/%[\d.]*[a-z@]/g, "");

/** True for a literal of ASCII punctuation alone, which nothing reads as words wherever it is. */
const isPunctuation = (text) => isAscii(wordsOf(text)) && !/[A-Za-z0-9]/.test(wordsOf(text));

/** True for a literal shaped like a key, identifier, route, URL, number or format — not words. */
export function isName(text) {
  const words = wordsOf(text);
  // Punctuation and digits, in ASCII: a glyph a voter sees or hears is not ASCII punctuation.
  if (!/\p{L}/u.test(words)) return isAscii(words);
  // No name holds a space.
  if (/\s/.test(text)) return false;
  // A route, with its query; a URL, or a URL template.
  if (/^\/\S*$/.test(text) || /^[a-z][a-z0-9+.-]*:\S*$/.test(text) || text.includes("://")) {
    return true;
  }
  // A single capital letter: an SVG path command, say.
  if (/^[A-Z]$/.test(text)) return true;
  // An identifier in CamelCase with a second capital: a type, plugin or object name, or a key
  // prefix made from one (`CapacitorStorage.`).
  if (/^[A-Z][a-z0-9]+[A-Z][A-Za-z0-9]*[.:_-]?$/.test(text) && text !== "How2Vote") return true;
  // One token that reads as a key — lower-case first, or joined by separators no word needs, and
  // ending in a word character, never in punctuation — including one built from values
  // (`lede-\(id)-`).
  const token = text.replace(/\{\}/g, "x");
  return /^[a-z_]\w*(?:[.:/-]\w+)*-?$/.test(token) || /^[A-Za-z]\w*(?:[._:]\w+)+$/.test(token);
}

/** True when error text is written as a diagnostic: its first letter lower-case, as copy's is not. */
const isDiagnostic = (text) => /^[^\p{L}]*(?:\p{Ll}|$)/u.test(text.replace(/\{\}/g, ""));

/** The inheritance clause of the type declared at a node, read from the source by its range. */
function inheritance(decl, lines) {
  const m = /range=\[[^:\]]+:(\d+):(\d+)/.exec(decl.head);
  if (!m) return "";
  const from = lines
    .slice(Number(m[1]) - 1)
    .join("\n")
    .slice(Number(m[2]) - 1);
  return /^[^{]*/
    .exec(from)[0]
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\/\/.*$/gm, "");
}

const TYPE_DECLS = new Set([
  "enum_decl",
  "struct_decl",
  "class_decl",
  "extension_decl",
  "actor_decl",
]);

/**
 * The nearest call a literal is an argument of, with the argument's label and position; null when
 * a closure or a statement block comes first, since what a closure returns is not the call's
 * argument.
 */
function enclosingCall(path) {
  for (let i = path.length - 1; i >= 0; i--) {
    const node = path[i];
    if (node.kind === "closure_expr" || (node.kind === "brace_stmt" && !isImplicit(node))) {
      return null;
    }
    // A subscript's argument is a key.
    const isCall = node.kind === "call_expr" && !interpolationStep(node) && !isImplicit(node);
    if (!isCall && node.kind !== "subscript_expr") continue;
    if (path[i + 1]?.kind !== "argument_list") continue;
    const argument = path[i + 2];
    return {
      name: isCall ? callee(node) : "subscript",
      label: argument?.kind === "argument" ? attr(argument, "label") : null,
      // The literal is the argument itself, first in the list — not something inside it.
      isFirst: path.length === i + 3 && path[i + 1].children[0] === argument,
    };
  }
  return null;
}

/** True when a literal, by where it sits, is a key, an identifier or diagnostic text. */
function isExcused({ text, path }, { lines, model }) {
  const call = enclosingCall(path);
  const method = call ? call.name.slice(call.name.lastIndexOf(".") + 1) : "";
  if (call && DIAGNOSTIC_FUNCTIONS.has(call.name)) return true;
  if (call?.label && NAME_LABELS.has(call.label) && !/\s/.test(text)) return true;
  if (call && call.name.includes(".") && IDENTIFIER_METHODS.has(method)) return true;
  if (call?.isFirst && (KEY_CALLS.has(call.name) || (model && MODEL_KEY_CALLS.has(call.name)))) {
    return true;
  }

  // Error text: thrown, returned as an error type's description, or handed to a call that carries
  // errors. Excused only when written as a diagnostic, since an error's text can reach a screen.
  if (!isDiagnostic(text)) return false;
  if (path.some((n) => n.kind === "throw_stmt")) return true;
  if (call && (ERROR_CALLS.has(call.name) || (model && MODEL_ERROR_CALLS.has(call.name)))) {
    return true;
  }
  const accessor = path.findLastIndex(
    (n) => n.kind === "accessor_decl" && attr(n, "for") === "description",
  );
  if (accessor >= 0) {
    const owner = path.slice(0, accessor).findLast((n) => TYPE_DECLS.has(n.kind));
    if (owner && /\bError\b/.test(inheritance(owner, lines))) return true;
  }
  return false;
}

/** True when a literal is passed straight to a view or a modifier that draws or speaks it. */
function isDrawn({ path }) {
  const call = enclosingCall(path);
  if (!call) return false;
  const method = call.name.slice(call.name.lastIndexOf(".") + 1);
  // A view is built by its type's name (`Text(…)`), not by a method on a type (`Doc.load(…)`).
  if (/^[A-Z]/.test(method) && !NOT_DRAWN.has(call.name)) return true;
  return (
    (method.startsWith("accessibility") && !IDENTIFIER_METHODS.has(method)) ||
    DRAWN_MODIFIERS.has(method)
  );
}

const keyOf = (text) => text.replace(/\{\}|\s/g, "");

/**
 * The hand-written copy in one Swift source: every literal a person could read or hear, once per
 * occurrence.
 *
 * @param {string} dump  the `swiftc -dump-parse` of `everyBranch(source)`
 * @param {{ source: string, model?: boolean }} context  the source, and whether it is under `Model/`
 * @returns {string[]}
 */
export function handWrittenCopy(dump, { source, model = false }) {
  const literals = literalsOf(parseDump(dump));
  const lines = everyBranch(source).split("\n");
  const found = [];
  const parsed = new Map();
  for (const literal of literals) {
    parsed.set(keyOf(literal.text), (parsed.get(keyOf(literal.text)) ?? 0) + 1);
    if (isPunctuation(literal.text) || isExcused(literal, { lines, model })) continue;
    if (isName(literal.text) && !isDrawn(literal)) continue;
    found.push(literal.text);
  }
  // A literal the source holds and the parse does not account for — an enum's raw value, an
  // attribute's argument — has no position to excuse it: only its shape can.
  for (const text of lexLiterals(source)) {
    const key = keyOf(text);
    const left = parsed.get(key) ?? 0;
    if (left > 0) parsed.set(key, left - 1);
    else if (!isName(text)) found.push(text);
  }
  return found.sort();
}

/**
 * True for a screen that shows an error's description, which the scanner excuses as diagnostic
 * text and would then reach the voter unexamined. Knows the names a `catch` binds.
 */
export function showsAnError(source) {
  const code = source.replace(/\/\/.*$/gm, "").replace(/NSLog\([^\n]*\)/g, "");
  const bound = [...code.matchAll(/catch\s+(?:let\s+)?(\w+)/g)].map((m) => m[1]);
  const name = `(?:\\w*[eE]rror|${["error", ...bound].join("|")})\\b`;
  return (
    /\.localizedDescription\b/.test(code) ||
    new RegExp(`String\\(describing:\\s*${name}`).test(code) ||
    new RegExp(`\\\\\\(\\s*${name}`).test(code)
  );
}

const counts = (texts) => {
  const out = new Map();
  for (const t of texts) out.set(t, (out.get(t) ?? 0) + 1);
  return out;
};

/**
 * @param {Record<string, string[]>} current  file → its hand-written copy, once per occurrence
 * @param {Record<string, string[]>} debt  the recorded debt
 * @param {Record<string, string[]> | null} base  the hand-written copy in the PR base's Swift, if any
 * @returns {string[]}
 */
export function verifyNativeContent(current, debt, base) {
  const errors = [];
  for (const file of new Set([...Object.keys(current), ...Object.keys(debt)])) {
    const have = counts(current[file] ?? []);
    const listed = counts(debt[file] ?? []);
    for (const [text, n] of have) {
      const extra = n - (listed.get(text) ?? 0);
      if (extra > 0) {
        errors.push(
          `${file} writes "${text}" natively${extra > 1 ? ` ${extra} more times` : ""} — native ` +
            `screens show only what the web build supplies`,
        );
      }
    }
    for (const [text, n] of listed) {
      if (n > (have.get(text) ?? 0)) {
        errors.push(`${DEBT} lists "${text}" in ${file} more often than it is written — remove it`);
      }
    }
  }
  if (base) {
    const before = counts(Object.values(base).flat());
    for (const [text, n] of counts(Object.values(debt).flat())) {
      if (n > (before.get(text) ?? 0)) {
        errors.push(`${DEBT} grew: "${text}" is listed more often than the base holds it`);
      }
    }
  }
  return errors;
}

/** The total number of hand-written strings a debt record lists. */
export const debtSize = (debt) => Object.values(debt).reduce((n, texts) => n + texts.length, 0);

/**
 * The generator that owns a source, by `GENERATED`: null for a hand-written file. Throws when the
 * header and the register disagree, so a header cannot exempt a file no generator writes.
 */
export function generatorOf(file, source) {
  const named = GENERATOR_HEADER.exec(source)?.[1] ?? null;
  const owner = GENERATED[file] ?? null;
  if (named !== owner) {
    throw new Error(
      owner
        ? `${file} is generated by ${owner}, but its header names ${named ?? "no generator"}`
        : `${file} carries a generator's header, but no generator owns it`,
    );
  }
  return owner;
}

