#!/usr/bin/env node
/**
 * The iOS app shows no hand-written copy: every word a native screen shows comes from the web build.
 *
 * The native screens are a skeleton. Their text arrives from the web — projected pages
 * (`build-native-documents.mjs`), the site chrome handed over with each route, the datasets — so a
 * string literal in Swift that a person could read or hear is copy that no web register, review or
 * check ever saw.
 *
 * The literals are read from the compiler's own parse (`swiftc -dump-parse`), so raw strings,
 * multi-line strings, escapes and interpolations are what Swift makes of them, and a literal is
 * excused by where it sits in the syntax tree rather than by what precedes it on the line. The parse
 * omits some literals (enum raw values, attribute arguments), and omits every `#if` body, so:
 *
 *   - conditional-compilation directives are blanked before parsing, and every branch is read;
 *   - every literal is also read from the source text, and one the parse does not account for is
 *     counted as copy, with no excusal.
 *
 * Every literal is counted unless it is plainly not copy:
 *
 *   - diagnostic text in a log or crash (`NSLog`, `fatalError`, …);
 *   - error text — thrown, an error type's description, a plugin's reject — written as a
 *     diagnostic: starting lower-case, as no sentence shown to a voter does;
 *   - a key or event name passed as one (`call.getString("electionId")`), an identifier, or a
 *     resource name (`systemName:`);
 *   - punctuation and format strings of ASCII alone;
 *   - a token shaped like a key, route, URL or type name — unless it is passed straight to a view or
 *     an accessibility modifier, where it is drawn or heard.
 *
 * Counting everything and excusing by kind fails closed: a new way of putting text on screen is
 * counted without this file having to know about it.
 *
 * Screens built before this rule still hold copy. It is listed in
 * `apps/mobile/ios/native-copy-debt.json`, once per occurrence, and the list may only shrink:
 *
 *   - an occurrence not in the list fails, so no new copy can be written natively;
 *   - a listed occurrence no longer in the source fails too, so the list stays exact as debt is paid;
 *   - with `NATIVE_CONTENT_BASE` set (the PR base, in CI), a string listed more often than the base's
 *     own Swift holds it, across all files, fails — so the list cannot be edited to admit new copy,
 *     while a file can still be renamed or split. The base is scanned with this scanner, so copy it
 *     newly detects is recorded, not mistaken for new.
 *
 * The generated sources listed in `GENERATED` are exempt: each is rendered from the web's own sources
 * by the generator named, which CI runs. A generator's header on any other file fails.
 *
 * Needs `swiftc` (or `SWIFTC`); CI uses the Linux image's. The fixtures under
 * `scripts/fixtures/native-content/` are run through that compiler first, so a compiler whose parse
 * reads differently fails here rather than passing everything.
 *
 * Usage: `node scripts/check-native-content.mjs` to verify, `--write` to record the current debt,
 * `--write-fixtures` to regenerate the fixtures' dumps.
 */
